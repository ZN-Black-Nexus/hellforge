/// Shown for characters the font doesn't have.
const MISSING: [u8; 8] = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f, 0];

/// The 8 rows of a character's glyph.
pub fn glyph(c: char) -> &'static [u8; 8] {
    let v = c as u32;
    if (32..127).contains(&v) { &G[(v - 32) as usize] } else { &MISSING }
}

/// Width in pixels of the widest line of `s`.
pub fn text_width(s: &str) -> i32 {
    let (mut best, mut cur) = (0, 0);
    for c in s.chars() {
        if c == '\n' {
            best = best.max(cur);
            cur = 0;
        } else {
            cur += CHAR_W;
        }
    }
    let w = best.max(cur);
    if w > 0 { w - 1 } else { 0 }
}

/// Height in pixels of `s` (one [`LINE_H`] per line, the last one [`CHAR_H`]).
pub fn text_height(s: &str) -> i32 {
    let lines = 1 + s.chars().filter(|&c| c == '\n').count() as i32;
    (lines - 1) * LINE_H + CHAR_H
}
